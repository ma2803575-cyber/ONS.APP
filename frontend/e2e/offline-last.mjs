import puppeteer from 'puppeteer-core'
const base = process.argv[2] || 'http://localhost:8000'
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] })
const p = await b.newPage(); await p.setViewport({ width: 390, height: 844 })
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
await p.goto(base + '/home', { waitUntil: 'networkidle0' })
await p.evaluate(() => navigator.serviceWorker.ready); await sleep(12000)
await p.reload({ waitUntil: 'networkidle0' })
// read: open surah 2 at ayah 100, tap it, add a bookmark (online)
await p.goto(base + '/surah/2?g=100', { waitUntil: 'networkidle0' }); await sleep(2500)
await p.evaluate(() => document.querySelector('#a100').click()); await sleep(600)
await p.evaluate(() => [...document.querySelectorAll('button')].find((x) => x.innerText.includes('علامة مرجعية')).click()); await sleep(800)
console.log('saved last =', await p.evaluate(() => localStorage.getItem('ons_g_last')), 'bookmarks =', await p.evaluate(() => localStorage.getItem('ons_g_bookmarks')))
await p.setOfflineMode(true)
await p.goto(base + '/quran', { waitUntil: 'networkidle0' }); await sleep(1500)
console.log('QURAN:', (await p.evaluate(() => document.body.innerText.replace(/\n/g, ' | '))).slice(0, 200))
await p.screenshot({ path: '/downloads/off-quran-last.png' })
await p.goto(base + '/bookmarks', { waitUntil: 'networkidle0' }); await sleep(1500)
console.log('BOOKMARKS:', (await p.evaluate(() => document.body.innerText.replace(/\n/g, ' | '))).slice(0, 200))
await p.screenshot({ path: '/downloads/off-bookmarks.png' })
await b.close()
