import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] })
const p = await b.newPage(); await p.setViewport({width:390,height:844})
await p.goto('http://localhost:8000/surah/1', { waitUntil: 'networkidle0' })
await new Promise(r=>setTimeout(r,2500))
const sw = await p.evaluate(async()=>{const r=await navigator.serviceWorker.ready; return r.active?.state})
const man = await p.evaluate(async()=>{const m=await (await fetch('/manifest.webmanifest')).json(); return m.name})
const ic = await p.evaluate(async()=>(await fetch('/icon-192.png')).headers.get('content-type'))
console.log('sw',sw,'manifest',man,'icon',ic)
await p.goto('http://localhost:8000/surah/1', { waitUntil: 'networkidle0' }); await new Promise(r=>setTimeout(r,1000))
await p.setOfflineMode(true)
await p.reload({ waitUntil: 'networkidle0' }).catch(e=>console.log('reload err',e.message))
await new Promise(r=>setTimeout(r,1500))
const t = await p.evaluate(()=>document.body.innerText.slice(0,200))
console.log('OFFLINE TEXT:', t.replace(/\n/g,' | '))
await b.close()
